client.once("ready", () => {
  console.log(`Logged in as ${client.user.tag}`);
});

client.on("messageCreate", async (message) => {
  if (message.author.bot) return;

  const msg = message.content.trim().toLowerCase();

  if (msg === "خط") {
    return message.channel.send({
      embeds: [new EmbedBuilder().setColor(0x6c2cff).setImage(LINE_IMAGE)]
    });
  }

  if (msg === "قوانين") {
    const embed = new EmbedBuilder()
      .setColor(0x6c2cff)
      .setTitle("📜 قوانين سيرفر R7")
      .setDescription("اختر قسم القوانين من القائمة بالأسفل 👇")
      .setImage(LINE_IMAGE)
      .setFooter({ text: "SERVER R7 | Rules Panel" });

    const menu = new StringSelectMenuBuilder()
      .setCustomId("rules_menu")
      .setPlaceholder("اختر قسم القوانين")
      .addOptions(
        { label: "القوانين العامة", description: "الاحترام والنظام العام", value: "general", emoji: "📖" },
        { label: "قوانين الشات", description: "قوانين الكتابة والتفاعل", value: "chat", emoji: "💬" },
        { label: "قوانين الفويس", description: "قوانين الرومات الصوتية", value: "voice", emoji: "🎧" },
        { label: "قوانين الأمن", description: "الحماية والروابط والحسابات", value: "security", emoji: "🛡️" },
        { label: "قوانين الإدارة", description: "قوانين طاقم الإدارة", value: "staff", emoji: "👑" }
      );

    return message.channel.send({
      embeds: [embed],
      components: [new ActionRowBuilder().addComponents(menu)]
    });
  }
});

